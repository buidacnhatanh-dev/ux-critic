import { demoSourceLine } from "./demo-source";

describe("demoSourceLine", () => {
  it("says written by hand when there are no reviews yet", () => {
    expect(demoSourceLine([])).toBe("Sample reviews written by hand");
  });

  it("says written by hand for handwritten reviews", () => {
    expect(demoSourceLine([{ kind: "handwritten" }])).toBe("Sample reviews written by hand");
  });

  it("says written by hand when sources are mixed", () => {
    expect(
      demoSourceLine([{ kind: "handwritten" }, { kind: "claude", generatedAt: "2026-11-03" }]),
    ).toBe("Sample reviews written by hand");
  });

  it("names the latest generation date when all reviews came from Claude", () => {
    expect(
      demoSourceLine([
        { kind: "claude", generatedAt: "2026-11-01T10:00:00Z" },
        { kind: "claude", generatedAt: "2026-11-03T09:00:00Z" },
      ]),
    ).toBe("Reviews generated by Claude on 3 Nov 2026");
  });
});
